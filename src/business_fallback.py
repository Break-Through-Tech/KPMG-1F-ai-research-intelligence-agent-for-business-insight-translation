"""Muse Wonder 1.0 fallback for business insight generation (Hydrogen stays primary).

Evaluated 29 Nov 2026 on the nine Hydrogen validation cases with the unchanged v1.2 prompt and the same
structural safeguards (evaluation-records/muse-wonder-fallback-2026-11-29). The fallback runs only when
Hydrogen fails with an exhausted quota, a rate limit or a temporary failure after its permitted retry, and
only within the remaining request time. It never runs after a validation failure: validation happens after
generation returns, so a rejected output is never regenerated by another model. Spending is capped per UTC
day with a SQLite ledger that reserves the worst-case cost before every call, so concurrent requests cannot
overspend. Provider text is never kept; only sanitized categories, status codes and usage numbers are.
"""
import json
import os
import sqlite3
import time
import urllib.error
import urllib.request
from contextlib import closing
from datetime import datetime, timezone
from pathlib import Path

from src.business_generation import (AUTHENTICATION, INVALID_REQUEST, QUOTA_EXHAUSTED, RATE_LIMITED, TEMPORARY,
                                     UNKNOWN, BusinessProviderError, BusinessTranslationUnavailable, MODEL as PRIMARY)

MODEL = 'muse-wonder-1.0'
URL = 'https://api.meta.ai/v1/chat/completions'
REASONING_EFFORT = 'high'
MAX_OUTPUT_TOKENS = 16000  # includes reasoning tokens; observed 1.8k-2.9k per call in evaluation
PRICE_INPUT_PER_TOKEN, PRICE_OUTPUT_PER_TOKEN = 4.00 / 1e6, 20.00 / 1e6
DEFAULT_DAILY_CAP_USD = 5.00
REQUEST_BUDGET_SECONDS = 160  # Hydrogen + fallback must finish inside the 170 s development proxy budget
MIN_FALLBACK_SECONDS = 35     # observed Muse latency 15-29 s; never start a call that cannot finish
MAX_FALLBACK_TIMEOUT = 75
FALLBACK_TRIGGERS = {QUOTA_EXHAUSTED, RATE_LIMITED, TEMPORARY}


class FallbackBudgetExhausted(BusinessProviderError):
    def __init__(self):
        super().__init__(QUOTA_EXHAUSTED, provider_status='LOCAL_DAILY_CAP')


def worst_case_cost(prompt):
    # Conservative token estimate (3 characters per token) plus the full output cap.
    return round(len(prompt) / 3.0 * PRICE_INPUT_PER_TOKEN + MAX_OUTPUT_TOKENS * PRICE_OUTPUT_PER_TOKEN, 6)


class SpendLedger:
    """Daily Muse spend. reserve() books the worst case atomically; settle() replaces it with the actual cost."""

    def __init__(self, path, daily_cap_usd=DEFAULT_DAILY_CAP_USD, clock=time.time):
        self.path, self.cap, self.clock = Path(path), float(daily_cap_usd), clock
        with closing(sqlite3.connect(self.path)) as store, store:
            store.execute('CREATE TABLE IF NOT EXISTS spend (id INTEGER PRIMARY KEY, day TEXT NOT NULL, '
                          'reserved REAL NOT NULL, actual REAL, at REAL NOT NULL)')

    def _day(self):
        return datetime.fromtimestamp(self.clock(), timezone.utc).strftime('%Y-%m-%d')

    def spent_today(self):
        with closing(sqlite3.connect(self.path, timeout=5)) as store:
            value, = store.execute('SELECT COALESCE(SUM(COALESCE(actual, reserved)), 0) FROM spend WHERE day = ?',
                                   (self._day(),)).fetchone()
        return round(value, 6)

    def reserve(self, amount):
        with closing(sqlite3.connect(self.path, timeout=5)) as store, store:
            store.execute('BEGIN IMMEDIATE')  # serializes concurrent reservations
            used, = store.execute('SELECT COALESCE(SUM(COALESCE(actual, reserved)), 0) FROM spend WHERE day = ?',
                                  (self._day(),)).fetchone()
            if used + amount > self.cap:
                raise FallbackBudgetExhausted()
            return store.execute('INSERT INTO spend (day, reserved, at) VALUES (?, ?, ?)',
                                 (self._day(), amount, self.clock())).lastrowid

    def settle(self, reservation, actual):
        with closing(sqlite3.connect(self.path, timeout=5)) as store, store:
            store.execute('UPDATE spend SET actual = ? WHERE id = ?', (round(actual, 6), reservation))


def _classify_http(status):
    if status in (500, 502, 503, 504):
        return TEMPORARY
    if status == 429:
        return RATE_LIMITED
    if status == 402:
        return QUOTA_EXHAUSTED
    if status in (401, 403):
        return AUTHENTICATION
    if isinstance(status, int) and 400 <= status < 500:
        return INVALID_REQUEST
    return UNKNOWN


def create_muse_generate(api_key, ledger, *, opener=None):
    """Return muse(prompt, timeout) -> JSON text. One attempt; usage and cost on muse.last_usage."""
    if not isinstance(api_key, str) or not api_key.strip():
        raise ValueError('A Meta Model API key is required for the Muse fallback.')
    send = opener or (lambda request, timeout: urllib.request.urlopen(request, timeout=timeout))

    def muse(prompt, timeout):
        muse.last_usage = None
        reservation = ledger.reserve(worst_case_cost(prompt))
        actual = 0.0
        body = {'model': MODEL, 'messages': [{'role': 'user', 'content': prompt}], 'reasoning_effort': REASONING_EFFORT,
                'max_completion_tokens': MAX_OUTPUT_TOKENS, 'temperature': 0, 'response_format': {'type': 'json_object'}}
        request = urllib.request.Request(URL, data=json.dumps(body).encode(), method='POST', headers={
            'Authorization': 'Bearer ' + api_key, 'Content-Type': 'application/json'})
        started = time.perf_counter()
        try:
            with send(request, timeout) as response:
                data = json.load(response)
        except urllib.error.HTTPError as error:
            ledger.settle(reservation, 0.0)  # rejected requests are not billed
            raise BusinessProviderError(_classify_http(error.code), http_status=error.code) from None
        except (TimeoutError, urllib.error.URLError, OSError):
            # Unknown billing for a timed-out request: keep the worst-case reservation.
            raise BusinessProviderError(TEMPORARY) from None
        usage = data.get('usage') or {}
        tokens_in, tokens_out = int(usage.get('prompt_tokens') or 0), int(usage.get('completion_tokens') or 0)
        actual = tokens_in * PRICE_INPUT_PER_TOKEN + tokens_out * PRICE_OUTPUT_PER_TOKEN
        ledger.settle(reservation, actual)
        muse.last_usage = {
            'input_tokens': tokens_in, 'output_tokens': tokens_out,
            'reasoning_tokens': int((usage.get('completion_tokens_details') or {}).get('reasoning_tokens') or 0),
            'estimated_cost_usd': round(actual, 6), 'seconds': round(time.perf_counter() - started, 1),
            'finish_reason': (data.get('choices') or [{}])[0].get('finish_reason')}
        try:
            return data['choices'][0]['message']['content']
        except (KeyError, IndexError, TypeError):
            return ''  # empty output fails validation; never retried on another model

    muse.last_usage = None
    return muse


def with_fallback(primary, muse, *, clock=time.monotonic, budget_seconds=REQUEST_BUDGET_SECONDS):
    """Hydrogen first; Muse only for quota/rate/temporary failures with enough time left.

    Attributes after each call: generator_used (model, fallback_from, fallback_reason, usage),
    fallback_failure (sanitized), provider_attempts and attempt_log (primary's).
    """

    def generate(prompt):
        started = clock()
        generate.generator_used = {'model': PRIMARY}
        generate.fallback_failure = None
        try:
            return primary(prompt)
        except BusinessProviderError as failure:
            reason = failure.category
            if reason not in FALLBACK_TRIGGERS or muse is None:
                raise
            remaining = budget_seconds - (clock() - started)
            if remaining < MIN_FALLBACK_SECONDS:
                generate.fallback_failure = {'category': 'skipped', 'reason': 'insufficient_time'}
                raise
            try:
                text = muse(prompt, min(MAX_FALLBACK_TIMEOUT, remaining - 5))
            except BusinessProviderError as fallback:
                generate.fallback_failure = fallback.diagnostics()
                # The reader sees "temporarily unavailable"; the research answer is retained.
                raise BusinessTranslationUnavailable(category=TEMPORARY, http_status=failure.http_status,
                                                     provider_status=failure.provider_status) from None
            generate.generator_used = {'model': MODEL, 'reasoning_effort': REASONING_EFFORT,
                                       'fallback_from': PRIMARY, 'fallback_reason': reason,
                                       'usage': getattr(muse, 'last_usage', None)}
            return text
        finally:
            for name in ('provider_attempts', 'attempt_log'):
                if hasattr(primary, name):
                    setattr(generate, name, getattr(primary, name))

    generate.generator_used, generate.fallback_failure = None, None
    return generate


def fallback_from_environment(state_dir, environ=None):
    """Build the Muse fallback from the environment, or return None when it is not configured."""
    env = os.environ if environ is None else environ
    if env.get('BUSINESS_FALLBACK_ENABLED', '1').strip().lower() in {'0', 'false', 'no'}:
        return None
    key = env.get('META_MODEL_API_KEY', '').strip()
    if not key:
        return None
    try:
        cap = float(env.get('MUSE_DAILY_CAP_USD', DEFAULT_DAILY_CAP_USD))
    except ValueError:
        cap = DEFAULT_DAILY_CAP_USD
    return create_muse_generate(key, SpendLedger(Path(state_dir) / 'muse-spend.sqlite3', max(0.0, cap)))
